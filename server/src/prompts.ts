export interface SystemOptions {
  mode: Mode
  novelTitle: string
  styleNote: string
  glossary: { source: string; thai: string; note: string }[]
  recaps: { number: number; recap: string }[]
}

/** ลำดับ: บทบาท → งาน (ตามโหมด) → กติกา → กติกาภาษาไทย → สไตล์ → อภิธาน → เรื่องย่อ ส่วนที่ไม่มีข้อมูลไม่ปรากฏทั้งหัวข้อ */
export function buildSystem(o: SystemOptions): string {
  const parts = [
    `คุณเป็นนักแปลและนักเล่านิยายภาษาไทยมืออาชีพ กำลังทำงานกับนิยายออนไลน์ภาษาอังกฤษเรื่อง "${o.novelTitle}" เพื่อเผยแพร่ให้ผู้อ่านชาวไทยอ่านบนเว็บไซต์`,
    `งานของคุณ: ${MODE_RULES[o.mode]}`,
    [SECTION_TITLES.rules, ...RULES.map((r) => `- ${r}`)].join("\n"),
    [SECTION_TITLES.thai, ...THAI_RULES.map(([label, text], i) => `${i + 1}. ${label}: ${text}`)].join("\n"),
  ]

  const style = o.styleNote.trim()
  if (style) parts.push(`${SECTION_TITLES.style}\n${style}`)

  if (o.glossary.length) {
    const lines = o.glossary.map((g) => `- ${g.source} → ${g.thai}${g.note ? ` (${g.note})` : ""}`)
    parts.push([SECTION_TITLES.glossary, ...lines].join("\n"))
  }

  const recaps = [...o.recaps].sort((a, b) => a.number - b.number).slice(-MAX_RECAPS)
  if (recaps.length) {
    parts.push([SECTION_TITLES.recaps, ...recaps.map((r) => `ตอนที่ ${r.number}: ${r.recap}`)].join("\n"))
  }

  return parts.join("\n\n")
}

/** ข้อความผู้ใช้ของชิ้นหนึ่ง: ลำดับชิ้น + ท้ายผลลัพธ์ชิ้นก่อน (ถ้ามี) + ต้นฉบับของชิ้นนี้ */
export function buildUserChunk(o: { chunk: string; index: number; total: number; previousTail?: string }): string {
  const tail = o.previousTail?.trim()
  const parts = [`ชิ้นที่ ${o.index + 1}/${o.total} ของตอนนี้`]
  if (tail) {
    parts.push(`ท้ายผลลัพธ์ของชิ้นก่อนหน้า (ไว้ให้เขียนต่อเนื่องเท่านั้น ห้ามเขียนซ้ำ):\n<previous_output_tail>\n${tail}\n</previous_output_tail>`)
  }
  parts.push(`<source_text>\n${o.chunk}\n</source_text>`)
  parts.push(tail ? "ตอบเฉพาะเนื้อหาภาษาไทยของข้อความต้นฉบับชิ้นนี้ โดยเขียนต่อจากท้ายผลลัพธ์ข้างต้นให้ลื่นไหล" : "ตอบเฉพาะเนื้อหาภาษาไทยของข้อความต้นฉบับชิ้นนี้")
  return parts.join("\n\n")
}


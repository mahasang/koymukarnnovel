/** ข้อความผู้ใช้ของการสรุปตอน: <source_text> และ <known_terms> ใส่เฉพาะเมื่อมีข้อมูล */
export function buildRecapUser(o: { thaiText: string; sourceTitle: string; sourceText?: string; knownTerms?: string[] }): string {
  const parts: string[] = []
  const title = o.sourceTitle.trim()
  if (title) parts.push(`ชื่อตอนต้นฉบับ: ${title}`)
  parts.push(`<thai_text>\n${o.thaiText}\n</thai_text>`)
  if (o.sourceText?.trim()) parts.push(`<source_text>\n${o.sourceText}\n</source_text>`)
  if (o.knownTerms?.length) parts.push(`<known_terms>\n${o.knownTerms.join("\n")}\n</known_terms>`)
  return parts.join("\n\n")
}
